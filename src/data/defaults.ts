export function isMissionUnlocked(
  missionId: string,
  progress: Record<string, MissionProgressRecord>
): boolean {
  const target = MISSIONS.find((m) => m.id === missionId);
  if (target?.alwaysUnlocked) return true;
  const ordered = [...MISSIONS]
    .filter((m) => !m.alwaysUnlocked)
    .sort((a, b) => a.storyOrder - b.storyOrder);
  const idx = ordered.findIndex((m) => m.id === missionId);
  if (idx < 0) return true; // side discovery mission unlocked once discovered
  if (idx === 0) return true;
  const prevMission = ordered[idx - 1];
  return (progress[prevMission.id]?.completedCount ?? 0) > 0;
}

